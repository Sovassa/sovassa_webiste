// 4. WebMCP tools via navigator.modelContext.registerTool()
// ---------------------------------------------------------------------------

/**
 * Register WebMCP tools on every front-end page.
 *
 * Each call to navigator.modelContext.registerTool() tells in-browser agents
 * what actions are available on the site. The scanner looks for at least one
 * call on page load.
 *
 * Tools registered:
 *   - get_quote   → navigates user to the Get-a-Quote form
 *   - contact     → navigates user to the Contact page
 *   - search_site → opens the site's search
 */
function sovassa_webmcp_tools_script() {
	if ( is_admin() ) {
		return;
	}
	$quote_url   = esc_js( home_url( '/get-a-quote/' ) );
	$contact_url = esc_js( home_url( '/contact/' ) );
	$search_url  = esc_js( home_url( '/?s=' ) );
	?>
<script>
(function () {
  if (!navigator.modelContext || typeof navigator.modelContext.registerTool !== 'function') {
    return;
  }

  /* Tool 1 – Request a project quote */
  navigator.modelContext.registerTool({
    name: 'get_quote',
    description: 'Navigate the user to the Sovassa Technologies project-quote request form so they can describe their project and receive a tailored proposal.',
    inputSchema: {
      type: 'object',
      properties: {
        service: {
          type: 'string',
          description: 'Optional service area the user is interested in, e.g. "web development" or "SEO".'
        }
      },
      required: []
    },
    execute: function (params) {
      var url = '<?php echo $quote_url; ?>';
      if (params && params.service) {
        url += '?service=' + encodeURIComponent(params.service);
      }
      window.location.href = url;
      return { navigated: true, url: url };
    }
  });

  /* Tool 2 – Open the Contact page */
  navigator.modelContext.registerTool({
    name: 'contact_sovassa',
    description: 'Open the Sovassa Technologies contact page so the user can send a message, find the phone number, email, or office address.',
    inputSchema: {
      type: 'object',
      properties: {},
      required: []
    },
    execute: function () {
      window.location.href = '<?php echo $contact_url; ?>';
      return { navigated: true, url: '<?php echo $contact_url; ?>' };
    }
  });

  /* Tool 3 – Search the site */
  navigator.modelContext.registerTool({
    name: 'search_site',
    description: 'Search the Sovassa Technologies website for articles, services, or case studies matching a query.',
    inputSchema: {
      type: 'object',
      properties: {
        query: {
          type: 'string',
          description: 'The search term to look up on the site.'
        }
      },
      required: ['query']
    },
    execute: function (params) {
      var url = '<?php echo $search_url; ?>' + encodeURIComponent(params.query || '');
      window.location.href = url;
      return { navigated: true, url: url };
    }
  });
})();
</script>
	<?php
}
add_action( 'wp_footer', 'sovassa_webmcp_tools_script', 5 );

