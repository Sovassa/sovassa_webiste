// Link header: advertise llms.txt and the MCP card to agents
// ---------------------------------------------------------------------------

/**
 * Send Link headers so agents can discover the Markdown endpoint and MCP card
 * without parsing HTML.
 *
 * @param array<string, string> $headers Response headers.
 * @return array<string, string>
 */
function sovassa_ai_link_headers( $headers ) {
	$llms = home_url( '/llms.txt' );
	$card = home_url( '/.well-known/mcp/server-card.json' );
	$md   = home_url( '/' ); // same URL, served as markdown on Accept: text/markdown

	$headers['Link'] = isset( $headers['Link'] ) ? $headers['Link'] : '';
	$parts = array_filter( explode( ',', $headers['Link'] ) );

	$parts[] = "<{$llms}>; rel=\"ai-content\"; type=\"text/plain\"";
	$parts[] = "<{$card}>; rel=\"mcp-server-card\"";
	$parts[] = "<{$md}>; rel=\"alternate\"; type=\"text/markdown\"";

	$headers['Link'] = implode( ', ', $parts );
	return $headers;
}
add_filter( 'wp_headers', 'sovassa_ai_link_headers' );
