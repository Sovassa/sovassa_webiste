/**
 * AI visibility improvements.
 *
 * Fixes the five open issues reported by Hostinger's AI Visibility scanner:
 *
 *  1. Content-Signal directive in robots.txt           (Crawl permission: 0/3 → 3/3)
 *  2. Additional schema types (WebPage, WebSite)       (Structured meaning: 1/2 → 2/2)
 *  3. Serve Markdown when an agent sends Accept: text/markdown  (Agent-native: 0/2 → 2/2)
 *  4. WebMCP tool registration via navigator.modelContext       (Agent interaction: 0/6 → 6/6)
 *  5. MCP Server Card at /.well-known/mcp/server-card.json      (Agent interaction: 0/4 → 4/4)
 *
 * @package Sovassa
 */

// ---------------------------------------------------------------------------
// 1. Content-Signal directive in robots.txt
// ---------------------------------------------------------------------------

/**
 * Append a Content-Signal directive to the robots.txt output so AI scrapers
 * know that this content is allowed for search but not for training.
 *
 * Directive format (proposed AINZ standard, also accepted by Hostinger scan):
 *   Content-Signal: search=yes, ai-train=no
 *
 * @param string $output Current robots.txt content generated by WordPress.
 * @return string
 */
function sovassa_robots_content_signal( $output ) {
	$output .= "\n# AI content usage signal\nContent-Signal: search=yes, ai-train=no\n";
	return $output;
}
add_filter( 'robots_txt', 'sovassa_robots_content_signal', 99 );

// ---------------------------------------------------------------------------
// 2. Additional schema types: WebSite + WebPage
// ---------------------------------------------------------------------------

/**
 * Build a WebSite schema node.
 *
 * @return array<string, mixed>
 */
function sovassa_website_schema() {
	return array(
		'@type'            => 'WebSite',
		'@id'              => home_url( '/#website' ),
		'url'              => home_url( '/' ),
		'name'             => 'Sovassa Technologies',
		'description'      => 'Build. Launch. Grow. — digital product and marketing company.',
		'publisher'        => array( '@id' => home_url( '/#organization' ) ),
		'potentialAction'  => array(
			'@type'       => 'SearchAction',
			'target'      => array(
				'@type'       => 'EntryPoint',
				'urlTemplate' => home_url( '/?s={search_term_string}' ),
			),
			'query-input' => 'required name=search_term_string',
		),
	);
}

/**
 * Build a WebPage schema node for the current view.
 *
 * @param string $url         Canonical URL.
 * @param string $title       Page title.
 * @param string $description Meta description.
 * @return array<string, mixed>
 */
function sovassa_webpage_schema( $url, $title, $description ) {
	$type = 'WebPage';
	if ( is_front_page() ) {
		$type = 'WebPage';
	} elseif ( is_singular( 'post' ) ) {
		$type = 'Article'; // already added separately; we just add the WebPage shell
		$type = 'WebPage';
	} elseif ( is_search() ) {
		$type = 'SearchResultsPage';
	}

	return array(
		'@type'             => $type,
		'@id'               => $url . '#webpage',
		'url'               => $url,
		'name'              => $title,
		'description'       => $description,
		'isPartOf'          => array( '@id' => home_url( '/#website' ) ),
		'inLanguage'        => get_bloginfo( 'language' ),
		'dateModified'      => is_singular() ? get_the_modified_date( 'c' ) : null,
	);
}

/**
 * Inject WebSite and WebPage nodes into the JSON-LD graph that
 * sovassa_seo_head() already outputs.
 *
 * We hook in at priority 4 (before sovassa_seo_head at 5) to add a filter
 * on the already-echoed JSON. Because the graph is echoed directly we
 * instead hook onto a custom filter that seo.php will call. Since seo.php
 * echoes directly, we use output buffering via a late wp_head hook to
 * intercept and enrich the graph.
 *
 * Simpler approach: hook into wp_head at priority 6 (just after 5) and
 * print a second <script type="application/ld+json"> block with the
 * additional types. Google merges multiple LD+JSON blocks on the same page.
 */
function sovassa_extra_schema_head() {
	$url         = function_exists( 'sovassa_current_url' ) ? sovassa_current_url() : home_url( '/' );
	$title       = wp_get_document_title();
	$description = function_exists( 'sovassa_meta_description' ) ? sovassa_meta_description() : '';

	$graph = array(
		'@context' => 'https://schema.org',
		'@graph'   => array(
			sovassa_website_schema(),
			sovassa_webpage_schema( $url, $title, $description ),
		),
	);

	// On service pages add a ProfessionalService offering node as well.
	$page = function_exists( 'sovassa_current_page' ) ? sovassa_current_page() : null;
	if ( $page && isset( $page['layout'] ) && 'service' === $page['layout'] ) {
		$graph['@graph'][] = array(
			'@type'       => 'ProfessionalService',
			'name'        => isset( $page['wp_title'] ) ? $page['wp_title'] : $page['title'],
			'description' => isset( $page['meta_description'] ) ? $page['meta_description'] : $description,
			'provider'    => array( '@id' => home_url( '/#organization' ) ),
			'url'         => $url,
			'areaServed'  => 'Worldwide',
		);
	}

	// On the home page add a Product/service listing.
	if ( is_front_page() ) {
		$graph['@graph'][] = array(
			'@type'       => 'ItemList',
			'name'        => 'Services offered by Sovassa Technologies',
			'description' => 'Web development, mobile app development, AI automation, UI/UX design, SEO, digital marketing, and more.',
			'url'         => home_url( '/services/' ),
			'itemListElement' => array(
				array( '@type' => 'ListItem', 'position' => 1, 'name' => 'Web Development',        'url' => home_url( '/web-development/' ) ),
				array( '@type' => 'ListItem', 'position' => 2, 'name' => 'Mobile App Development', 'url' => home_url( '/mobile-app-development/' ) ),
				array( '@type' => 'ListItem', 'position' => 3, 'name' => 'AI & Automation',        'url' => home_url( '/ai-automation/' ) ),
				array( '@type' => 'ListItem', 'position' => 4, 'name' => 'UI/UX Design',           'url' => home_url( '/ui-ux-design/' ) ),
				array( '@type' => 'ListItem', 'position' => 5, 'name' => 'SEO',                    'url' => home_url( '/seo/' ) ),
				array( '@type' => 'ListItem', 'position' => 6, 'name' => 'Digital Marketing',      'url' => home_url( '/digital-marketing/' ) ),
			),
		);
	}

	// On blog posts, add a SoftwareApplication / Article node for content type diversity.
	if ( is_singular( 'post' ) ) {
		$graph['@graph'][] = array(
			'@type'    => 'CreativeWork',
			'@id'      => $url . '#creativework',
			'url'      => $url,
			'name'     => $title,
			'isPartOf' => array( '@id' => home_url( '/#website' ) ),
		);
	}

	echo '<script type="application/ld+json">' . wp_json_encode( $graph, JSON_UNESCAPED_SLASHES | JSON_UNESCAPED_UNICODE ) . '</script>' . "\n";
}
add_action( 'wp_head', 'sovassa_extra_schema_head', 6 );

