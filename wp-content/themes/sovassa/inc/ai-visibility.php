/**
 * Register the rewrite rule that maps /.well-known/mcp/server-card.json to a
 * WordPress query var, then serve the JSON payload.
 */
function sovassa_mcp_server_card_rewrite() {
	add_rewrite_rule(
		'^\.well-known/mcp/server-card\.json$',
		'index.php?sovassa_mcp_card=1',
		'top'
	);
}
add_action( 'init', 'sovassa_mcp_server_card_rewrite' );

/**
 * Register the custom query var.
 *
 * @param array<int, string> $vars Existing public query vars.
 * @return array<int, string>
 */
function sovassa_mcp_query_vars( $vars ) {
	$vars[] = 'sovassa_mcp_card';
	return $vars;
}
add_filter( 'query_vars', 'sovassa_mcp_query_vars' );

/**
 * Serve the MCP Server Card JSON when the query var is set.
 */
function sovassa_serve_mcp_server_card() {
	if ( ! get_query_var( 'sovassa_mcp_card' ) ) {
		return;
	}

	$card = array(
		'$schema'     => 'https://spec.modelcontextprotocol.io/server-card/v1',
		'name'        => 'Sovassa Technologies MCP Server',
		'version'     => '1.0.0',
		'description' => 'MCP server for Sovassa Technologies – a digital product and marketing agency. Provides tools to request quotes, search services, and retrieve company information.',
		'url'         => home_url( '/' ),
		'contact'     => array(
			'email' => 'admin@sovassa.com',
			'url'   => home_url( '/contact/' ),
		),
		'capabilities' => array(
			'tools'     => true,
			'resources' => false,
			'prompts'   => false,
		),
		'tools' => array(
			array(
				'name'        => 'get_quote',
				'description' => 'Navigate the user to the project quote request form.',
				'inputSchema' => array(
					'type'       => 'object',
					'properties' => array(
						'service' => array(
							'type'        => 'string',
							'description' => 'Optional service area, e.g. "web development".',
						),
					),
					'required'   => array(),
				),
			),
			array(
				'name'        => 'contact_sovassa',
				'description' => 'Open the contact page to reach Sovassa Technologies.',
				'inputSchema' => array(
					'type'       => 'object',
					'properties' => new stdClass(),
					'required'   => array(),
				),
			),
			array(
				'name'        => 'search_site',
				'description' => 'Search the website for services, articles, or case studies.',
				'inputSchema' => array(
					'type'       => 'object',
					'properties' => array(
						'query' => array(
							'type'        => 'string',
							'description' => 'Search term.',
						),
					),
					'required'   => array( 'query' ),
				),
			),
		),
		'legalInfo' => array(
			'privacyPolicy'  => home_url( '/privacy/' ),
			'termsOfService' => home_url( '/terms/' ),
		),
	);

	if ( ! headers_sent() ) {
		header( 'Content-Type: application/json; charset=utf-8' );
		header( 'Cache-Control: public, max-age=86400' );
		header( 'Access-Control-Allow-Origin: *' );
	}

	echo wp_json_encode( $card, JSON_UNESCAPED_SLASHES | JSON_UNESCAPED_UNICODE | JSON_PRETTY_PRINT );
	exit;
}
add_action( 'template_redirect', 'sovassa_serve_mcp_server_card', 2 );

/**
 * Flush rewrite rules when the theme is activated (or updated), so the
 * /.well-known/mcp/server-card.json rule takes effect immediately.
 */
function sovassa_flush_on_switch() {
	sovassa_mcp_server_card_rewrite();
	flush_rewrite_rules( false );
}
add_action( 'after_switch_theme', 'sovassa_flush_on_switch' );

