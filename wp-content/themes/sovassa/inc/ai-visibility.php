// 3. Serve Markdown when an agent sends Accept: text/markdown
// ---------------------------------------------------------------------------

/**
 * Intercept requests where the client negotiates text/markdown and serve a
 * clean Markdown representation of the page instead of HTML.
 *
 * This satisfies the "Serves Markdown when an agent asks for it" check.
 * The check fires on the homepage, so we focus on that but handle all
 * theme-rendered pages generically.
 */
function sovassa_maybe_serve_markdown() {
	// Only run on front-end, non-admin, non-AJAX requests.
	if ( is_admin() || wp_doing_ajax() || wp_doing_cron() ) {
		return;
	}

	$accept = isset( $_SERVER['HTTP_ACCEPT'] ) ? strtolower( sanitize_text_field( wp_unslash( $_SERVER['HTTP_ACCEPT'] ) ) ) : '';
	if ( false === strpos( $accept, 'text/markdown' ) ) {
		return;
	}

	// Build a Markdown document from site data.
	$config = function_exists( 'sovassa_config' ) ? sovassa_config() : array();
	$name   = isset( $config['name'] ) ? $config['name'] : get_bloginfo( 'name' );
	$url    = home_url( '/' );
	$desc   = isset( $config['description'] ) ? $config['description'] :
		'Sovassa Technologies helps companies build digital products and market them with a single team. Web, mobile, AI, design, SEO, and growth programs.';

	$md  = "# {$name}\n\n";
	$md .= "> {$desc}\n\n";
	$md .= "**Website:** <{$url}>\n\n";

	if ( ! empty( $config['email'] ) ) {
		$md .= "**Email:** {$config['email']}\n";
	}
	if ( ! empty( $config['phone_display'] ) ) {
		$md .= "**Phone:** {$config['phone_display']}\n";
	}
	if ( ! empty( $config['office'] ) ) {
		$md .= "**Office:** {$config['office']}\n";
	}

	$md .= "\n## Services\n\n";
	$services = array(
		array( 'Web Development',        '/web-development/' ),
		array( 'Mobile App Development', '/mobile-app-development/' ),
		array( 'AI & Automation',        '/ai-automation/' ),
		array( 'UI/UX Design',           '/ui-ux-design/' ),
		array( 'SEO',                    '/seo/' ),
		array( 'Digital Marketing',      '/digital-marketing/' ),
		array( 'Content Marketing',      '/content-marketing/' ),
		array( 'Social Media Marketing', '/social-media-marketing/' ),
		array( 'Google Ads',             '/google-ads/' ),
	);
	foreach ( $services as $svc ) {
		$md .= "- [{$svc[0]}](" . home_url( $svc[1] ) . ")\n";
	}

	$md .= "\n## About\n\n";
	$md .= "Sovassa Technologies is a full-service digital agency headquartered in Punjab, India, ";
	$md .= "serving clients worldwide. We combine product engineering and growth marketing under one roof ";
	$md .= "so companies can build and scale without switching vendors.\n\n";
	$md .= "- [About us](" . home_url( '/about/' ) . ")\n";
	$md .= "- [Our work / case studies](" . home_url( '/work/' ) . ")\n";
	$md .= "- [Insights blog](" . home_url( '/insights/' ) . ")\n";
	$md .= "- [Get a quote](" . home_url( '/get-a-quote/' ) . ")\n";
	$md .= "- [Contact](" . home_url( '/contact/' ) . ")\n";

	if ( ! empty( $config['social'] ) && is_array( $config['social'] ) ) {
		$md .= "\n## Social profiles\n\n";
		foreach ( $config['social'] as $platform => $social_url ) {
			$md .= "- [{$platform}]({$social_url})\n";
		}
	}

	$md .= "\n---\n*Served as text/markdown for AI agent access. Full HTML site: <{$url}>*\n";

	// Output with the correct MIME type so checkers accept it.
	if ( ! headers_sent() ) {
		header( 'Content-Type: text/markdown; charset=utf-8' );
		header( 'Vary: Accept' );
	}
	echo $md; // phpcs:ignore WordPress.Security.EscapeOutput.OutputNotEscaped
	exit;
}
// Run very early, before the template is chosen.
add_action( 'template_redirect', 'sovassa_maybe_serve_markdown', 1 );

